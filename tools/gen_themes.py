"""Build src/styles/themes.css + src/lib/themes.ts from tui-design theme JSON files.
Usage: python3 tools/extra_themes.py && python3 tools/gen_themes.py tools/themes
(tools/themes holds the tui-design skill themes plus the ones tools/extra_themes.py writes)"""
import json, sys, pathlib

src = pathlib.Path(sys.argv[1]).expanduser()
out = pathlib.Path(__file__).resolve().parent.parent
DEFAULT = 'vitesse-black'  # :root fallback and dark-system default; light systems get vitesse-light

def hx(h): h = h.lstrip('#'); return [int(h[i:i+2], 16) for i in (0, 2, 4)]
def mix(a, b, t):  # t of a over b
    return '#' + ''.join(f'{round(x*t + y*(1-t)):02x}' for x, y in zip(hx(a), hx(b)))

SPEC = json.loads((src / '_tokens.json').read_text())['tokens']
def fb(k):  # spec fallback chain; bg.stripe has none, use bg.surface
    return SPEC.get(k, {}).get('fallback') or {'bg.stripe': 'bg.surface'}.get(k)

def lum(h):
    c = [x / 255 for x in hx(h)]
    c = [x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4 for x in c]
    return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]
def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True); return (la + .05) / (lb + .05)
def floor(c, bg, need):
    # push a text color toward black/white (away from bg) until it meets the WCAG floor
    end = '#000000' if lum(bg) > .4 else '#ffffff'; t = 0
    while ratio(c, bg) < need and t < 1:
        t += .02; c2 = mix(end, c, t)
        if ratio(c2, bg) >= need: return c2
    return c if t == 0 else mix(end, c, t)
TEXT = {'foreground': 4.5, 'foreground-muted': 4.5, 'foreground-subtle': 3, 'accent': 4.5,
        'success': 4.5, 'warning': 4.5, 'danger': 4.5, 'info': 4.5, 'accent-2': 4.5, 'title': 4.5}
nudged = {}

css, meta = [], []
for f in sorted(src.glob('*.json')):
    if f.name.startswith('_'): continue
    d = json.loads(f.read_text())
    pal = d.get('palette', {})
    def tok(k):
        while k not in d['tokens']: k = fb(k)
        v = d['tokens'][k]
        return v if v.startswith('#') else pal[v]
    bg, fg, acc, bd = tok('bg.base'), tok('fg.default'), tok('accent.primary'), tok('border.default')
    v = {
        'background': bg, 'background-subtle': tok('bg.stripe'),
        'surface': tok('bg.surface'), 'surface-raised': tok('bg.raised'),
        'surface-overlay': tok('bg.overlay'), 'surface-selected': tok('selection.bg'),
        'foreground': fg, 'foreground-muted': tok('fg.muted'), 'foreground-subtle': tok('fg.faint'),
        'foreground-inverted': tok('fg.on-accent'), 'foreground-selected': tok('selection.fg'),
        'border': bd, 'border-subtle': mix(bd, bg, .55), 'border-strong': tok('fg.faint'),
        'accent': acc, 'accent-foreground': tok('fg.on-accent'), 'accent-subtle': mix(acc, bg, .18),
        'accent-2': tok('accent.secondary'),
        'success': tok('status.success'), 'warning': tok('status.warning'),
        'danger': tok('status.error'), 'info': tok('status.info'),
        'focus': tok('border.focus'), 'selection': tok('text-selection.bg'),
        'hover': tok('selection.inactive.bg'), 'title': tok('fg.title'),
    }
    for k, need in TEXT.items():
        n = floor(v[k], bg, need)
        if n != v[k]: nudged.setdefault(d['id'], []).append(k); v[k] = n
    # text on accent: keep the theme's on-accent unless black/white reads better
    v['accent-foreground'] = v['foreground-inverted'] = max([v['foreground-inverted'], bg, '#000000', '#ffffff'], key=lambda c: (ratio(c, v['accent']) >= 4.5, c in (v['foreground-inverted'], bg), ratio(c, v['accent'])))
    # the theme's six terminal colours (ANSI slots 1-6: red, green, yellow, blue, magenta, cyan),
    # held to the text contrast floor so they work as text colours
    ansi = d['terminal']['ansi']
    for i in range(1, 7):
        v[f'hue-{i}'] = floor(ansi[i], bg, 4.5)
    light = d['appearance'] == 'light'
    body = ' '.join(f'--{k}:{c};' for k, c in v.items())
    body += f" --grain:{'.38' if light else '.15'}; --grain-blend:{'multiply' if light else 'normal'}; color-scheme:{d['appearance']};"
    sel = f'[data-theme="{d["id"]}"]'
    if d['id'] == DEFAULT: sel = ':root, ' + sel
    css.append(f'{sel} {{ {body} }}')
    meta.append({'id': d['id'], 'name': d['name'], 'scheme': d['scheme'], 'variant': d['variant'],
                 'appearance': d['appearance'], 'sw': [bg, fg] + [v[f'hue-{i}'] for i in range(1, 7)]})

# default first so :root fallback is not overridden by source order
css.sort(key=lambda s: not s.startswith(':root'))
(out / 'src/styles/themes.css').write_text('/* generated by tools/gen_themes.py from tui-design themes. do not edit */\n' + '\n'.join(css) + '\n')
(out / 'src/lib/themes.ts').write_text('/* generated by tools/gen_themes.py. do not edit */\nimport type { Theme } from "./theme-types"\n\nexport const THEMES: Array<Theme> = ' + json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + '\n\nexport const DEFAULT_THEME = "' + DEFAULT + '"\n')
print(len(meta), 'themes')
for k, x in nudged.items(): print(' nudged', k, ', '.join(x))
